/**
 * Get barangays for a specific city/municipality
 * Case-insensitive search
 */
export function getBarangays(city: string): string[] {
  if (!city) return [];
  
  // Try exact match first
  if (barangayData[city]) {
    return barangayData[city];
  }
  
  // Try case-insensitive match
  const cityLower = city.toLowerCase().trim();
  const matchedKey = Object.keys(barangayData).find(
    key => key.toLowerCase() === cityLower
  );
  
  return matchedKey ? barangayData[matchedKey] : [];
}

/**
 * Get all available cities
 */
export function getCities(): string[] {
  return Object.keys(barangayData).sort();
}
